"use client";

import { useEffect, useState } from "react";
import { Check, Download, FileText } from "lucide-react";
import { downloadCsv, downloadMarkdown, fetchInvestigations } from "@/lib/ofi/api";
import type { InvestigationDTO } from "@/lib/ofi/types";
import { CardSkeleton, ErrorState, ViewHeader } from "../shared";
import { cn } from "@/lib/utils";

function reportMarkdown(selected: InvestigationDTO[], all: InvestigationDTO[]) {
  const lines: string[] = [];
  lines.push("# OFI Research Summary Report", "");
  lines.push(`_Generated by Orbital Flame Intelligence — ${new Date().toLocaleString()}_`, "");
  lines.push(`Scope: ${selected.length} of ${all.length} verified corpus records.`, "");
  lines.push(
    "> All content is extracted from verified public NASA and peer-reviewed sources in the OFI corpus.",
    "> OFI does not fabricate measurements, citations or DOIs. OFI scores are OFI-defined metadata heuristics.",
    "",
  );
  for (const inv of selected) {
    lines.push(`## ${inv.code} — ${inv.name}`, "");
    lines.push(`- **Category:** ${inv.category}`);
    lines.push(`- **Status:** ${inv.status}`);
    lines.push(`- **Platform:** ${inv.platform}`);
    lines.push(`- **Facility:** ${inv.facility}`);
    lines.push(`- **Gravity condition:** ${inv.gravityCondition}`);
    lines.push(`- **Launch year:** ${inv.launchYear ?? "Not dated in source"}`);
    if (inv.doi) lines.push(`- **DOI:** ${inv.doi}`);
    lines.push(`- **Research areas:** ${inv.researchAreas.join("; ")}`);
    lines.push(`- **Fuels & materials:** ${inv.fuelsMaterials.join("; ")}`);
    lines.push(`- **OFI score:** overall ${inv.score.overall} (DQ ${inv.score.dataQuality} / REL ${inv.score.scientificRelevance} / COMP ${inv.score.completeness} / MQ ${inv.score.metadataQuality})`);
    lines.push("", "**Objective.** " + inv.objective, "");
    lines.push("**Key findings (as stated in sources):**", "");
    inv.keyFindings.forEach((f) => lines.push(`- ${f}`));
    lines.push("", "**Sources:**", "");
    inv.sources.forEach((s) => lines.push(`- ${s.title} — ${s.authors}${s.year ? `, ${s.year}` : ""}, ${s.venue}${s.doi ? ` — DOI ${s.doi}` : ""}`));
    lines.push("", "---", "");
  }
  return lines.join("\n");
}

export default function ReportsView() {
  const [items, setItems] = useState<InvestigationDTO[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [selected, setSelected] = useState<Set<string>>(new Set());
  const [done, setDone] = useState<string | null>(null);

  useEffect(() => {
    fetchInvestigations({ pageSize: 50, sort: "name" })
      .then((r) => {
        setItems(r.items);
        setSelected(new Set(r.items.slice(0, 3).map((i) => i.code)));
      })
      .catch((e) => setError(e.message));
  }, []);

  const chosen = (items ?? []).filter((i) => selected.has(i.code));

  const exportMarkdown = () => {
    downloadMarkdown(`ofi-research-report-${new Date().toISOString().slice(0, 10)}.md`, reportMarkdown(chosen, items ?? []));
    setDone("report");
    setTimeout(() => setDone(null), 2000);
  };

  const exportCatalogueCsv = () => {
    downloadCsv("ofi-catalogue.csv", [
      ["Code", "Name", "Category", "Status", "Platform", "Facility", "Gravity", "Launch year", "DOI", "Overall score", "Sources"],
      ...(items ?? []).map((i) => [
        i.code, i.name, i.category, i.status, i.platform, i.facility, i.gravityCondition,
        i.launchYear ?? "", i.doi ?? "", i.score.overall, i.sources.length,
      ]),
    ]);
    setDone("catalogue");
    setTimeout(() => setDone(null), 2000);
  };

  return (
    <div className="mx-auto max-w-7xl">
      <ViewHeader
        eyebrow="Workspace · Reports"
        title="Research Reports"
        description="Compose and download research summary reports from verified corpus records, or export the full catalogue as CSV. Reports carry provenance statements and cite every source."
      />

      {error && <ErrorState message={error} />}
      {!items && !error && <div className="grid gap-4 md:grid-cols-2">{[0, 1, 2, 3].map((i) => <CardSkeleton key={i} />)}</div>}

      {items && (
        <div className="grid grid-cols-1 gap-6 lg:grid-cols-[1fr_320px]">
          {/* selector */}
          <div className="ofi-card p-6">
            <div className="flex items-center justify-between">
              <p className="ofi-mono text-[10px] tracking-[0.2em] text-[#91A4BD] uppercase">
                Select records ({selected.size}/{items.length})
              </p>
              <div className="flex gap-2">
                <button
                  onClick={() => setSelected(new Set(items.map((i) => i.code)))}
                  className="text-[11px] text-[#42D9FF] hover:underline focus-visible:outline-none"
                >
                  Select all
                </button>
                <span className="text-[#5B708C]">·</span>
                <button
                  onClick={() => setSelected(new Set())}
                  className="text-[11px] text-[#91A4BD] hover:underline focus-visible:outline-none"
                >
                  Clear
                </button>
              </div>
            </div>
            <div className="ofi-scroll mt-4 grid max-h-[420px] grid-cols-1 gap-2 overflow-y-auto pr-1 sm:grid-cols-2">
              {items.map((inv) => {
                const on = selected.has(inv.code);
                return (
                  <button
                    key={inv.code}
                    onClick={() => {
                      const next = new Set(selected);
                      if (on) next.delete(inv.code);
                      else next.add(inv.code);
                      setSelected(next);
                    }}
                    aria-pressed={on}
                    className={cn(
                      "flex items-start gap-3 rounded-xl border p-3.5 text-left transition-colors focus-visible:ring-2 focus-visible:ring-[#42D9FF] focus-visible:outline-none",
                      on ? "border-[#42D9FF]/45 bg-[rgba(66,217,255,0.07)]" : "border-[rgba(140,190,230,0.12)] hover:border-[#42D9FF]/30",
                    )}
                  >
                    <span className={cn(
                      "mt-0.5 flex h-4 w-4 shrink-0 items-center justify-center rounded border",
                      on ? "border-[#42D9FF] bg-[#42D9FF] text-[#050914]" : "border-[rgba(140,190,230,0.3)]",
                    )}>
                      {on && <Check className="h-3 w-3" />}
                    </span>
                    <span className="min-w-0">
                      <span className="ofi-mono block text-[10px] text-[#42D9FF]">{inv.code}</span>
                      <span className="block truncate text-xs text-[#F4F8FF]">{inv.name}</span>
                    </span>
                  </button>
                );
              })}
            </div>
          </div>

          {/* export panel */}
          <aside className="space-y-4">
            <div className="ofi-card p-6">
              <p className="ofi-mono text-[10px] tracking-[0.2em] text-[#91A4BD] uppercase">Generate</p>
              <button
                onClick={exportMarkdown}
                disabled={chosen.length === 0}
                className="mt-4 flex w-full items-center gap-3 rounded-lg bg-gradient-to-r from-[#42D9FF] to-[#397BFF] px-4 py-3 text-xs font-semibold text-[#050914] transition-transform hover:scale-[1.02] disabled:opacity-40 disabled:hover:scale-100 focus-visible:outline-none"
              >
                {done === "report" ? <Check className="h-4 w-4" /> : <FileText className="h-4 w-4" />}
                {done === "report" ? "Report downloaded" : `Research report (${chosen.length} records)`}
              </button>
              <button
                onClick={exportCatalogueCsv}
                className="mt-3 flex w-full items-center gap-3 rounded-lg border border-[rgba(140,190,230,0.2)] px-4 py-3 text-xs text-[#F4F8FF] transition-colors hover:border-[#42D9FF]/50 focus-visible:outline-none"
              >
                {done === "catalogue" ? <Check className="h-4 w-4 text-[#42D9FF]" /> : <Download className="h-4 w-4 text-[#42D9FF]" />}
                {done === "catalogue" ? "Catalogue exported" : "Export full catalogue (CSV)"}
              </button>
              {chosen.length === 0 && (
                <p className="mt-3 text-[10px] leading-relaxed text-[#5B708C]">
                  Select at least one record to generate a report.
                </p>
              )}
            </div>

            <div className="ofi-card p-6">
              <p className="ofi-mono text-[10px] tracking-[0.2em] text-[#91A4BD] uppercase">Report contents</p>
              <ul className="mt-3 space-y-2 text-[11px] leading-relaxed text-[#91A4BD]">
                {[
                  "Per-record objective, conditions and platform metadata",
                  "Key findings exactly as stated in verified sources",
                  "Full source list with venue and DOI where verified",
                  "OFI score with the honest methodology disclaimer",
                ].map((t) => (
                  <li key={t} className="flex gap-2">
                    <span className="mt-1.5 h-1 w-1 shrink-0 rounded-full bg-[#42D9FF]" />
                    {t}
                  </li>
                ))}
              </ul>
            </div>
          </aside>
        </div>
      )}
    </div>
  );
}
